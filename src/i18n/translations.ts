export function translate(lang: Lang, key: TranslationKey, vars?: Record<string, string>): string {
  let s = translations[lang][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v);
    }
  }
  return s;
}